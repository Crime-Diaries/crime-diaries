/* Builds data/world.js: simplified country outlines (1:110m) with ISO 3166 alpha-3 codes, for the globe's
   homicide-rate layer. Run once: node scripts/build-world.mjs   (Node 18+, no dependencies)
   Outlines: world-atlas 2.0.2 (Natural Earth, public domain). Codes: i18n-iso-countries 7.11.0 (MIT).
   The rates themselves are fetched live by the browser from the World Bank, so this file rarely needs rebuilding. */
import { writeFile } from 'node:fs/promises';

const get = async u => { const r = await fetch(u); if (!r.ok) throw new Error(`${u}: ${r.status}`); return r.json() };
const topo = await get('https://cdn.jsdelivr.net/npm/world-atlas@2.0.2/countries-110m.json');
const codes = await get('https://cdn.jsdelivr.net/npm/i18n-iso-countries@7.11.0/codes.json');
const iso3 = Object.fromEntries(codes.map(([, a3, num]) => [num, a3]));
/* shapes without a numeric code: Kosovo has a World Bank code; the others have no data of their own */
const BY_NAME = { Kosovo: 'XKX' };

/* decode TopoJSON arcs (delta-encoded, quantized) into plain coordinates */
const { scale: [sx, sy], translate: [tx, ty] } = topo.transform;
const arcs = topo.arcs.map(arc => { let x = 0, y = 0; return arc.map(([dx, dy]) => [(x += dx) * sx + tx, (y += dy) * sy + ty]) });
const r2 = n => Math.round(n * 100) / 100;
const ring = ids => {
  const pts = [];
  ids.forEach((i, k) => {
    const a = i < 0 ? arcs[~i].slice().reverse() : arcs[i];
    a.forEach((p, j) => { if (k > 0 && j === 0) return; pts.push([r2(p[0]), r2(p[1])]) });
  });
  /* rounding can make neighbouring points equal; Cesium refuses a ring with repeated points, so drop them */
  /* -180° and 180° are the same meridian, so those count as repeats too */
  const same = (a, b) => a[1] === b[1] && (a[0] === b[0] || (Math.abs(a[0]) === 180 && Math.abs(b[0]) === 180));
  const out = pts.filter((p, i) => i === 0 || !same(p, pts[i - 1]));
  while (out.length > 1 && same(out[0], out[out.length - 1])) out.pop();
  out.push(out[0]); /* GeoJSON rings end where they start */
  return out;
};
const keep = rings => rings.filter(r => r.length >= 4);
/* Antarctica has no homicide data and its pole-hugging outline cannot be drawn on the globe's surface */
const features = topo.objects.countries.geometries.filter(g => g.properties.name !== 'Antarctica').map(g => ({
  type: 'Feature',
  properties: { name: g.properties.name, iso3: iso3[g.id] || BY_NAME[g.properties.name] || null },
  geometry: g.type === 'Polygon'
    ? { type: 'Polygon', coordinates: keep(g.arcs.map(ring)) }
    : { type: 'MultiPolygon', coordinates: g.arcs.map(p => keep(p.map(ring))).filter(p => p.length) }
}));
const js = `/* Generated by scripts/build-world.mjs. Country outlines: Natural Earth 1:110m via world-atlas (public domain). */
window.WORLD = ${JSON.stringify({ type: 'FeatureCollection', features })};
`;
await writeFile(new URL('../data/world.js', import.meta.url), js);
console.log(`world.js: ${features.length} countries, ${features.filter(f => !f.properties.iso3).length} without a code, ${(js.length / 1024).toFixed(0)} KB`);
